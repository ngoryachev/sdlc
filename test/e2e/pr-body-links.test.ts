import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { FakeRunner } from '../fakes/fake-runner.js';
import { FakeGitHub } from '../fakes/fake-github.js';
import { makeRepo, sh, testApp, tmpDir } from '../helpers.js';

/** Writes one file so every commit phase has something to commit; answers every schema-bound phase with a skip. */
const runner = () => new FakeRunner((spec) => ({
  act: () => {
    const p = spec.prompt;
    if (p.includes('Phase: test')) return { structured: { verdict: 'skipped', summary: 'n/a', commands: [], tests_added: [], failures: [], notes: '' } };
    if (p.includes('Phase: review')) return { structured: { verdict: 'approve', summary: 'ok', findings: [] } };
    if (p.includes('Phase: QA')) return { structured: { verdict: 'skipped', summary: 'n/a', checks: [], issues: [] } };
    if (p.includes('Phase: implement')) { fs.writeFileSync(path.join(spec.cwd, 'a.txt'), 'y\n'); return { text: 'implemented' }; }
    return { text: 'ok' };
  },
}));

/** A bare origin under a github.com-shaped path, so `repoSlug` is `me/shop` while pushes stay on the filesystem. */
function makeSlugRepo(dir: string, files: Record<string, string>): { repo: string; bare: string } {
  const repo = makeRepo(dir, files);
  const bare = path.join(dir, 'github.com', 'me', 'shop.git');
  fs.mkdirSync(path.dirname(bare), { recursive: true });
  sh(dir, ['init', '-q', '--bare', '-b', 'main', bare]);
  sh(repo, ['remote', 'add', 'origin', bare]);
  sh(repo, ['push', '-q', '-u', 'origin', 'main']);
  return { repo, bare };
}

const setup = async (prefix: string, o: { prompt?: string; jiraUrl?: string | null } = {}) => {
  const dir = tmpDir(prefix);
  const { repo, bare } = makeSlugRepo(dir, { 'a.txt': 'x\n' });
  const gh = new FakeGitHub(bare);
  const jira = o.jiraUrl === undefined ? 'https://x.atlassian.net' : o.jiraUrl;
  const app = testApp(dir, runner(), { repos: [{ name: 'shop', path: repo, gh_user: 'tester', ...(jira ? { jira_url: jira } : {}) }] }, gh);
  // `auto` opens no pull request: the task finishes and the PR is the human's own next step
  const t = await app.engine.createTask({ prompt: o.prompt ?? 'ABC-123 add a flag', repoPath: repo, pipeline: 'auto', baseRemote: 'origin' });
  await app.engine.advance(t.id);
  expect(app.store.getTask(t.id)!.status).toBe('succeeded');
  return { app, gh, task: app.store.getTask(t.id)! };
};

/**
 * The pull request a human opens from the task page (POST /tasks/:id/pr) renders the same body template as the `pr`
 * phase, through `Engine.prBody` instead of the phase: the links have to be there too.
 */
describe('the links in a pull request body opened by hand', () => {
  it('carries the issue and the branch', async () => {
    const { app, gh, task } = await setup('sdlc-manual-pr-links-');
    const after = await app.engine.createPrForTask(task.id);
    const body = gh.prs.get(after.prNumber!)!.body;
    expect(body).toContain('https://x.atlassian.net/browse/ABC-123');
    expect(body).toContain(`https://github.com/me/shop/tree/${after.branch}`);
  });

  it('leaves the issue out for a repository without jira_url, and the branch line alone leaves no gap', async () => {
    const { app, gh, task } = await setup('sdlc-manual-pr-nolinks-', { prompt: 'add a flag', jiraUrl: null });
    const after = await app.engine.createPrForTask(task.id);
    const body = gh.prs.get(after.prNumber!)!.body;
    expect(body).not.toContain('/browse/');
    expect(body).toContain(`https://github.com/me/shop/tree/${after.branch}\n\n---\nGenerated by sdlc · task \`${after.id}\``);
  });
});

/**
 * The body quotes the task prompt (and the plan, and the implement output) verbatim inside `<details>`. Blank lines
 * inside a fenced code block are part of that text: two of them is what PEP 8 asks for between two functions.
 */
describe('the quoted text in a pull request body', () => {
  const PROMPT = ['ABC-123 add a flag', '', '```python', 'def f():', '    pass', '', '', 'def g():', '    pass', '```'].join('\n');

  it('keeps the prompt exactly as the human wrote it', async () => {
    const { app, gh, task } = await setup('sdlc-pr-body-code-', { prompt: PROMPT });
    const after = await app.engine.createPrForTask(task.id);
    expect(gh.prs.get(after.prNumber!)!.body).toContain(PROMPT);
    expect(app.store.getTask(task.id)!.initialPrompt).toBe(PROMPT);
  });
});
